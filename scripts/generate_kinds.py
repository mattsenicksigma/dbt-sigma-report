#!/usr/bin/env python3
"""Generate macros/elements/kinds.sql: the element kinds Sigma's report schema defines, with the properties
each requires and allows.

    python scripts/generate_kinds.py            # rewrite macros/elements/kinds.sql
    python scripts/generate_kinds.py --check    # fail if the committed file is out of date

The source is the request schema bundled at integration_tests/schema/create_report_request.schema.json.gz
(extracted from Sigma's public OpenAPI document; refresh it with `validate_against_sigma_schema.py
--refresh`). The registry is what lets `sigma_report.raw()` and `sigma_report.extend()` reject an unknown
kind, a missing required property or a misspelt one at `dbt parse`, instead of at Sigma. CI runs `--check`,
so the registry cannot drift from the schema.
"""
import argparse
import gzip
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCHEMA = os.path.join(HERE, "..", "integration_tests", "schema", "create_report_request.schema.json.gz")
OUT = os.path.join(HERE, "..", "macros", "elements", "kinds.sql")

HEADER = """{# GENERATED by scripts/generate_kinds.py from Sigma's report request schema - do not edit by hand.
   Run `python scripts/generate_kinds.py` after refreshing the schema; CI fails if this file is stale.

   For every element kind a report can contain: the properties Sigma requires and all it allows.
   Used by `sigma_report.raw()` and `sigma_report.extend()` to validate raw Sigma properties. #}
"""


def load_schema():
    with gzip.open(SCHEMA, "rt") as handle:
        return json.load(handle)


def deref(schema, node):
    while isinstance(node, dict) and "$ref" in node:
        node = schema["components"]["schemas"][node["$ref"].split("/")[-1]]
    return node


def flatten(schema, node, props, required):
    """Collect the properties and required names of a (possibly allOf / oneOf) object schema."""
    node = deref(schema, node)
    for part in node.get("allOf", []):
        flatten(schema, part, props, required)
    for key, value in node.get("properties", {}).items():
        props[key] = value
    required.update(node.get("required", []))


def kinds(schema):
    """{kind: (sorted required, sorted all properties)} for every element kind in the schema."""
    out = {}

    def visit(node):
        node = deref(schema, node)
        parts = node.get("allOf", [])
        if len(parts) == 1 and "oneOf" in deref(schema, parts[0]):  # a titled wrapper around a union
            visit(parts[0])
            return
        if "oneOf" in node and "allOf" not in node:
            for option in node["oneOf"]:
                visit(option)
            return
        props, required = {}, set()
        flatten(schema, node, props, required)
        for option in node.get("oneOf", []):  # allOf + oneOf: the options add properties
            extra, extra_required = {}, set()
            flatten(schema, option, extra, extra_required)
            props.update(extra)
        kind = props.get("kind", {}).get("enum")
        if kind:
            out[kind[0]] = (sorted(required), sorted(props))

    visit(schema["components"]["schemas"]["ReportElement"])
    return dict(sorted(out.items()))


def render(schema):
    lines = [HEADER, "{% macro element_kinds() %}", "{% do return({"]
    for kind, (required, props) in kinds(schema).items():
        lines.append('  "%s": {"required": "%s", "properties": "%s"},' % (kind, ",".join(required), ",".join(props)))
    lines += ["}) %}", "{% endmacro %}", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if kinds.sql is not up to date")
    args = parser.parse_args(argv)
    text = render(load_schema())
    if args.check:
        with open(OUT) as handle:
            if handle.read() != text:
                print("macros/elements/kinds.sql is out of date - run `python scripts/generate_kinds.py`", file=sys.stderr)
                return 1
        print("kinds.sql is up to date")
        return 0
    with open(OUT, "w") as handle:
        handle.write(text)
    print("wrote %s (%d kinds)" % (OUT, text.count('"required"')))
    return 0


if __name__ == "__main__":
    sys.exit(main())
