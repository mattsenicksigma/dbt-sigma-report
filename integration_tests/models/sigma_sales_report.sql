{# The same package without the composites: pages, rows, header / footer panels, a pivot, a table
   with a calculated column, a chart built on another element, and the `extend` / `raw` escape
   hatches. Two pages, one of which paginates. #}
{% set orders = sigma_report.from_ref('stg_orders') %}

{% set detail = sigma_report.table(orders,
    ['order_id', 'order_date', 'region',
     sigma_report.field('[Amount]', name='Revenue', format=sigma_report.format_currency(2))],
    name='Orders', sort=[('order_date', 'desc')], h=420) %}

{% set revenue = sigma_report.kpi(orders, 'Sum([Amount])', name='Revenue',
    format=sigma_report.format_currency(), compare_to='Sum([Target Amount])') %}
{% set monthly = sigma_report.kpi(orders, 'CountDistinct([Order Id])', name='Orders',
    timeline='order_date', period='month', trend=true) %}

{% set by_region = sigma_report.extend(
    sigma_report.bar_chart(orders, 'region', 'Sum([Amount])', name='Revenue by region', horizontal=true, labels=true, h=200),
    {'gap': {'width': 'small'}}) %}
{% set by_month = sigma_report.line_chart(orders, 'DateTrunc("month", [Order Date])', 'Sum([Amount])',
    color='segment', name='Revenue by month') %}
{# a chart on a table that is already on the page #}
{% set top_orders = sigma_report.bar_chart(sigma_report.element(detail), 'order_id', 'Revenue',
    name='Largest orders', key='largest-orders') %}

{% set pivot = sigma_report.pivot_table(orders, 'Sum([Amount])', rows='region', cols='segment',
    name='Revenue by region and segment') %}

{% set embed = sigma_report.raw('embed', 'status-page', {'url': 'https://example.com/status'}, h=120) %}

{% set spec = sigma_report.report(
    name='Sales report',
    description='Hand-assembled report',
    page_size='a4',
    margin=40,
    theme={'hue': 'Emerald', 'categorical': ['#007a55', '#f54900', '#432dd7']},
    header=[sigma_report.row([
        sigma_report.text('**Acme Corp** | Sales', key='header-left', h=32),
        sigma_report.text('Confidential', key='header-right', h=32),
    ], widths=[3, 1])],
    footer=[sigma_report.text('Generated by dbt', key='footer-note', h=24)],
    pages=[
      sigma_report.page('Summary', [
        sigma_report.report_header('Sales summary', 'Hand-assembled from primitives'),
        sigma_report.row([sigma_report.stack([revenue, monthly]), by_month], widths=[1, 2]),
        by_region,
        sigma_report.section('Mix', [pivot]),
      ]),
      sigma_report.page('Detail', [
        sigma_report.heading('Order detail'),
        detail,
        top_orders,
        embed,
      ], paginate=true),
    ],
) %}

{{ sigma_report.materialize(spec) }}

select 1 as report
